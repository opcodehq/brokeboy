import { readFile, writeFile } from "node:fs/promises";
import { tables } from "../src/storage/contract.js";

const check = process.argv.includes("--check");
for (const dialect of ["postgres", "mysql", "sqlite"] as const) {
  const mysql = dialect === "mysql",
    pg = dialect === "postgres",
    table = pg ? "pgTable" : mysql ? "mysqlTable" : "sqliteTable";
  const imports = [
    table,
    ...(mysql ? [] : ["text"]),
    "primaryKey",
    "index",
    ...(mysql
      ? ["varchar", "longtext", "int", "bigint", "customType"]
      : pg
        ? ["integer", "bigint"]
        : ["integer"]),
  ];
  const lines = [
    `// Generated by scripts/generate-schema.ts.`,
    `import {${imports.sort().join(",")}} from "drizzle-orm/${pg ? "pg-core" : mysql ? "mysql-core" : "sqlite-core"}";`,
  ];
  lines.push("");
  if (mysql)
    lines.push(
      'const binaryId=customType<{data:string}>({dataType:()=>"varchar(191) CHARACTER SET ascii COLLATE ascii_bin"});',
    );
  const id = (name: string) =>
    mysql ? `binaryId("${name}")` : `text("${name}")`;
  const due = pg || mysql ? 'bigint("due",{mode:"number"})' : 'integer("due")';
  for (const name of tables) {
    const model = `billing${name[0]!.toUpperCase()}${name.slice(1)}`;
    lines.push(
      `export const ${model}=${table}("brokeboy_${name}",{scope:${id("scope")}.notNull(),id:${id("id")}.notNull(),state:${mysql ? 'varchar("state",{length:32})' : 'text("state")'}.notNull(),data:${mysql ? 'longtext("data")' : 'text("data")'}.notNull()${name === "work" ? `,due:${due}.notNull().default(0)` : ""}},t=>[primaryKey({columns:[t.scope,t.id]}),index("brokeboy_${name}_state").on(t.scope,t.state)${name === "work" ? ',index("brokeboy_work_due").on(t.scope,t.state,t.due,t.id)' : ""}]);`,
    );
  }
  lines.push(
    `export const billingLocks=${table}("brokeboy_locks",{scope:${id("scope")}.primaryKey(),revision:${mysql ? "int" : "integer"}("revision").notNull().default(0),token:${mysql ? 'varchar("token",{length:64})' : 'text("token")'}});`,
  );
  const source = `${lines.join("\n")}\n`;
  // Pass generated source via stdin rather than editing application files.
  const formatter = Bun.spawn(
    [
      "bunx",
      "biome",
      "format",
      "--stdin-file-path",
      `src/schemas/${dialect}.ts`,
    ],
    { stdin: new Blob([source]), stdout: "pipe", stderr: "pipe" },
  );
  const result = await new Response(formatter.stdout).text();
  if ((await formatter.exited) !== 0)
    throw new Error("Schema formatting failed");
  const path = `src/schemas/${dialect}.ts`;
  if (check) {
    if ((await readFile(path, "utf8")) !== result)
      throw new Error(`Schema drift: ${path}`);
  } else await writeFile(path, result);
}
